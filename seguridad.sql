
-- 1. CREACIÓN DE ROLES DE APLICACIÓN

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sv_junta') THEN
        CREATE ROLE sv_junta WITH LOGIN PASSWORD 'JuntaPass2026!';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sv_candidato') THEN
        CREATE ROLE sv_candidato WITH LOGIN PASSWORD 'CandidatoPass2026!';
    END IF;
END $$;


-- 2. POLÍTICA DE ACCESO MÍNIMO Y AISLAMIENTO DE TABLAS


REVOKE ALL ON ALL TABLES IN SCHEMA public FROM sv_junta, sv_candidato;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM sv_junta, sv_candidato;
REVOKE ALL ON SCHEMA public FROM sv_junta, sv_candidato;

GRANT USAGE ON SCHEMA public TO sv_junta, sv_candidato;


-- 3. AUTORIZACIONES PARA LA JUNTA ADMINISTRADORA (SV_JUNTA)

GRANT USAGE ON SCHEMA SV_JUNTA TO sv_junta;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_JUNTA TO sv_junta;

REVOKE ALL ON SCHEMA SV_CANDIDATO FROM sv_junta;


-- 4. AUTORIZACIONES PARA EL CANDIDATO (SV_CANDIDATO)

GRANT USAGE ON SCHEMA SV_CANDIDATO TO sv_candidato;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA SV_CANDIDATO TO sv_candidato;

REVOKE ALL ON SCHEMA SV_JUNTA FROM sv_candidato;
